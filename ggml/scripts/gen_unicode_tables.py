"""Generate ggml/src/unicode-tables.h from this Python's unicodedata (the reference package's).

Run from the repo root with the package venv: ``uv run python ggml/scripts/gen_unicode_tables.py``.

Tables (sorted, inclusive code-point ranges or sorted code points):
- wordy: general category L* or N* (``fusealign_hub.aligner._is_wordy``)
- space: ``str.isspace`` (``str.split()``)
- ascii key: code points whose ``ch.lower()`` keeps characters of [0-9a-z] under
  ``re.sub(r"[^0-9a-z]", "", ...)`` (``fusealign_hub.longform.approximate_times``' match key), with
  the kept characters. ``str.lower`` is per code point apart from Greek final sigma, which never maps
  to ASCII, so the key of a word is the concatenation of its code points' keys.
"""

from pathlib import Path
import re
import sys
import unicodedata

OUT = Path(__file__).resolve().parents[1] / "src" / "unicode-tables.h"


def ranges(predicate):
    out, lo = [], None
    for cp in range(0x110000 + 1):
        hit = cp <= 0x10FFFF and predicate(chr(cp))
        if hit and lo is None:
            lo = cp
        elif not hit and lo is not None:
            out.append((lo, cp - 1))
            lo = None
    return out


def emit_ranges(name, items):
    lines = [f"static const CodepointRange {name}[] = {{"]
    row = []
    for lo, hi in items:
        row.append(f"{{0x{lo:X}, 0x{hi:X}}},")
        if len(row) == 6:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("};")
    return lines


def main():
    wordy = ranges(lambda ch: unicodedata.category(ch)[0] in ("L", "N"))
    space = ranges(str.isspace)
    keys = []
    for cp in range(0x110000):
        key = re.sub(r"[^0-9a-z]", "", chr(cp).lower())
        if key:
            if len(key) != 1:
                sys.exit(f"U+{cp:04X} keys to {key!r}; the C++ table holds one character per code point")
            keys.append((cp, key))

    lines = [
        "// Generated by ggml/scripts/gen_unicode_tables.py; do not edit.",
        f"// Python {sys.version.split()[0]}, unicodedata {unicodedata.unidata_version}.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        "namespace fusealign::unicode {",
        "",
        "struct CodepointRange {",
        "    uint32_t lo;",
        "    uint32_t hi;  // inclusive",
        "};",
        "",
        "struct AsciiKey {",
        "    uint32_t cp;",
        "    char key;",
        "};",
        "",
        f'static const char UNIDATA_VERSION[] = "{unicodedata.unidata_version}";',
        "",
        "// General category L* or N*.",
        *emit_ranges("WORDY_RANGES", wordy),
        "",
        "// str.isspace().",
        *emit_ranges("SPACE_RANGES", space),
        "",
        '// re.sub(r"[^0-9a-z]", "", chr(cp).lower()) when non-empty, sorted by code point.',
        "static const AsciiKey ASCII_KEYS[] = {",
    ]
    row = []
    for cp, key in keys:
        row.append(f"{{0x{cp:X}, '{key}'}},")
        if len(row) == 8:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines += ["};", "", "}  // namespace fusealign::unicode", ""]
    OUT.write_text("\n".join(lines))
    print(f"{OUT}: {len(wordy)} wordy ranges, {len(space)} space ranges, {len(keys)} key code points")


if __name__ == "__main__":
    main()
